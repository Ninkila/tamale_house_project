def get_default_image_for_house(house_id):
    """Return a deterministic property photo URL based on the house identifier."""
    digits = "".join(ch for ch in str(house_id or "") if ch.isdigit())
    if digits:
        idx = int(digits) % len(DEFAULT_HOUSE_IMAGES)
    else:
        idx = abs(hash(str(house_id))) % len(DEFAULT_HOUSE_IMAGES)
    return DEFAULT_HOUSE_IMAGES[idx]


def get_connection():
    """Open a PostgreSQL connection using DATABASE_URL (or POSTGRES_URL)."""
    database_url = os.environ.get("DATABASE_URL") or os.environ.get("POSTGRES_URL")
    if not database_url:
        raise RuntimeError("Set DATABASE_URL to a PostgreSQL connection string.")
    return psycopg.connect(database_url, row_factory=dict_row)


def create_users_table():
    """Create the application's PostgreSQL schema, apply safe migrations, and seed initial properties."""
    with closing(get_connection()) as connection, connection:
        connection.execute("""
            CREATE TABLE IF NOT EXISTS users (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                username TEXT NOT NULL UNIQUE,
                email TEXT NOT NULL UNIQUE,
                full_name TEXT,
                phone TEXT DEFAULT '0241234567',
                show_whatsapp BOOLEAN NOT NULL DEFAULT TRUE,
                show_phone BOOLEAN NOT NULL DEFAULT TRUE,
                password_hash TEXT NOT NULL,
                role TEXT NOT NULL CHECK (role IN ('admin', 'landlord', 'tenant')),
                created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
        """)
        connection.execute("""
            CREATE UNIQUE INDEX IF NOT EXISTS users_username_lower_idx ON users (lower(username))
        """)
        connection.execute("""
            CREATE UNIQUE INDEX IF NOT EXISTS users_email_lower_idx ON users (lower(email))
        """)
        connection.execute("""
            CREATE TABLE IF NOT EXISTS properties (
                house_id TEXT PRIMARY KEY,
                neighborhood TEXT NOT NULL,
                house_type TEXT NOT NULL,
                rooms INTEGER NOT NULL,
                bathrooms INTEGER NOT NULL,
                furnishing TEXT,
                distance_from_central_tamale_km DOUBLE PRECISION,
                electricity TEXT,
                water TEXT,
                compound TEXT,
                monthly_rent_ghs DOUBLE PRECISION NOT NULL,
                landlord_id BIGINT REFERENCES users(id),
                landlord_phone TEXT DEFAULT '0241234567',
                show_whatsapp BOOLEAN NOT NULL DEFAULT TRUE,
                show_phone BOOLEAN NOT NULL DEFAULT TRUE,
                available BOOLEAN NOT NULL DEFAULT TRUE,
                image TEXT,
                title TEXT,
                description TEXT,
                created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
        """)
        connection.execute("""
            CREATE TABLE IF NOT EXISTS favourites (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                tenant_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                house_id TEXT NOT NULL REFERENCES properties(house_id) ON DELETE CASCADE,
                created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                UNIQUE (tenant_id, house_id)
            )
        """)
        connection.execute("""
            CREATE TABLE IF NOT EXISTS enquiries (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                property_id TEXT NOT NULL REFERENCES properties(house_id) ON DELETE CASCADE,
                tenant_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
                landlord_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
                tenant_name TEXT NOT NULL,
                tenant_email TEXT NOT NULL,
                message TEXT NOT NULL,
                status TEXT NOT NULL DEFAULT 'Pending',
                created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
        """)
        connection.execute("""
            CREATE TABLE IF NOT EXISTS traffic_events (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                visitor_id TEXT NOT NULL,
                page_path TEXT NOT NULL,
                created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
        """)

        # Idempotent column additions for existing installations
        connection.execute("ALTER TABLE properties ADD COLUMN IF NOT EXISTS available BOOLEAN NOT NULL DEFAULT TRUE")
        connection.execute("ALTER TABLE properties ADD COLUMN IF NOT EXISTS image TEXT")
        connection.execute("ALTER TABLE properties ADD COLUMN IF NOT EXISTS title TEXT")
        connection.execute("ALTER TABLE properties ADD COLUMN IF NOT EXISTS description TEXT")
        connection.execute("ALTER TABLE users ADD COLUMN IF NOT EXISTS phone TEXT DEFAULT '0241234567'")
        connection.execute("ALTER TABLE users ADD COLUMN IF NOT EXISTS show_whatsapp BOOLEAN NOT NULL DEFAULT TRUE")
        connection.execute("ALTER TABLE users ADD COLUMN IF NOT EXISTS show_phone BOOLEAN NOT NULL DEFAULT TRUE")
        connection.execute("ALTER TABLE users DROP CONSTRAINT IF EXISTS users_role_check")
        connection.execute("""
            ALTER TABLE users
            ADD CONSTRAINT users_role_check CHECK (role IN ('admin', 'landlord', 'tenant'))
        """)
        connection.execute("CREATE INDEX IF NOT EXISTS traffic_events_created_at_idx ON traffic_events (created_at DESC)")
        connection.execute("CREATE INDEX IF NOT EXISTS traffic_events_path_idx ON traffic_events (page_path)")
        sync_admin_roles(connection)

        seed_properties_if_empty(connection)


def configured_admin_emails():
    """Return normalized administrator emails from the server-side allowlist."""
    value = os.environ.get("ADMIN_EMAILS", "")
    return [email.strip().lower() for email in value.split(",") if email.strip()]


def sync_admin_roles(connection):
    """Promote explicitly configured existing accounts; registration can never create admins."""
    admin_emails = configured_admin_emails()
    if not admin_emails:
        return
    connection.execute(
        "UPDATE users SET role = 'admin' WHERE LOWER(email) = ANY(%s)",
        (admin_emails,),
    )


def record_traffic_event(connection, visitor_id, page_path):
    """Store a privacy-conscious page-view event without retaining IP addresses."""
    connection.execute(
        "INSERT INTO traffic_events (visitor_id, page_path) VALUES (%s, %s)",
        (visitor_id or uuid4().hex, page_path[:255]),
    )


def get_traffic_analytics(connection):
    """Return aggregate traffic and platform metrics for the protected admin dashboard."""
    traffic = connection.execute("""
        SELECT
            COUNT(*) AS page_views_30d,
            COUNT(DISTINCT visitor_id) AS unique_visitors_30d,
            COUNT(*) FILTER (WHERE created_at >= date_trunc('day', CURRENT_TIMESTAMP)) AS page_views_today
        FROM traffic_events
        WHERE created_at >= CURRENT_TIMESTAMP - INTERVAL '30 days'
    """).fetchone()
    platform = connection.execute("""
        SELECT
            (SELECT COUNT(*) FROM users) AS total_users,
            (SELECT COUNT(*) FROM properties WHERE available = TRUE) AS active_listings,
            (SELECT COUNT(*) FROM enquiries WHERE created_at >= CURRENT_TIMESTAMP - INTERVAL '30 days') AS enquiries_30d
    """).fetchone()
    daily = connection.execute("""
        SELECT
            TO_CHAR(days.day, 'Mon DD') AS label,
            COUNT(te.id) AS views,
            COUNT(DISTINCT te.visitor_id) AS visitors
        FROM generate_series(
            date_trunc('day', CURRENT_TIMESTAMP) - INTERVAL '6 days',
            date_trunc('day', CURRENT_TIMESTAMP),
            INTERVAL '1 day'
        ) AS days(day)
        LEFT JOIN traffic_events te
            ON te.created_at >= days.day
            AND te.created_at < days.day + INTERVAL '1 day'
        GROUP BY days.day
        ORDER BY days.day
    """).fetchall()
    pages = connection.execute("""
        SELECT page_path, COUNT(*) AS views
        FROM traffic_events
        WHERE created_at >= CURRENT_TIMESTAMP - INTERVAL '30 days'
        GROUP BY page_path
        ORDER BY views DESC, page_path ASC
        LIMIT 6
    """).fetchall()
    roles = connection.execute("""
        SELECT role, COUNT(*) AS count
        FROM users
        GROUP BY role
        ORDER BY role
    """).fetchall()
    recent_users = connection.execute("""
        SELECT username, email, full_name, role, created_at
        FROM users
        ORDER BY created_at DESC
        LIMIT 8
    """).fetchall()

    return {
        "summary": {**dict(traffic), **dict(platform)},
        "daily": [dict(row) for row in daily],
        "top_pages": [dict(row) for row in pages],
        "roles": [dict(row) for row in roles],
        "recent_users": [
            {**dict(row), "created_at": row["created_at"].isoformat()}
            for row in recent_users
        ],
    }


def _num(value, default, cast):
    try:
        if pd.isna(value):
            return default
        return cast(value)
    except (TypeError, ValueError):
        return default


def seed_properties_if_empty(connection):
    if connection.execute("SELECT EXISTS (SELECT 1 FROM properties)").fetchone()["exists"]:
        return
    if not CSV_PATH.exists():
        return

    df = pd.read_csv(CSV_PATH)
    with connection.cursor() as cursor:
        for _, row in df.iterrows():
            house_id = row.get("house_id")
            cursor.execute("""
                INSERT INTO properties (
                    house_id, neighborhood, house_type, rooms, bathrooms,
                    furnishing, distance_from_central_tamale_km, electricity,
                    water, compound, monthly_rent_ghs, available, image
                ) VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
                ON CONFLICT (house_id) DO NOTHING
            """, (
                house_id, row.get("neighborhood"), row.get("house_type"),
                _num(row.get("rooms"), 1, int), _num(row.get("bathrooms"), 1, int),
                row.get("furnishing"),
                _num(row.get("distance_from_central_tamale_km"), 5.0, float),
                row.get("electricity"), row.get("water"), row.get("compound"),
                _num(row.get("monthly_rent_ghs"), 0.0, float),
                True,
                get_default_image_for_house(house_id),
            ))


def format_property_dict(row):
    """Ensure consistent dictionary structure for properties across all API routes."""
    if not row:
        return None
    d = dict(row)
    house_id = d.get("house_id", "")
    if not d.get("image"):
        d["image"] = get_default_image_for_house(house_id)
    if not d.get("title"):
        d["title"] = f"{d.get('house_type', 'House')} in {d.get('neighborhood', 'Tamale')}"
    if d.get("available") is None:
        d["available"] = True
    if "created_at" in d and hasattr(d["created_at"], "isoformat"):
        d["created_at"] = d["created_at"].isoformat()
    return d


def query_properties(
    connection,
    budget=None,
    min_rent=None,
    max_rent=None,
    neighborhood=None,
    rooms=None,
    min_rooms=None,
    max_rooms=None,
    bathrooms=None,
    min_bathrooms=None,
    max_bathrooms=None,
    water=None,
    house_type=None,
    available_only=False,
    landlord_id=None,
):
    """Query properties from PostgreSQL with parameterized filtering."""
    sql = """
        SELECT
            p.house_id,
            p.neighborhood,
            p.house_type,
            p.rooms,
            p.bathrooms,
            p.furnishing,
            p.distance_from_central_tamale_km,
            p.electricity,
            p.water,
            p.compound,
            p.monthly_rent_ghs,
            p.landlord_id,
            COALESCE(p.landlord_phone, u.phone, '0241234567') AS landlord_phone,
            COALESCE(p.show_whatsapp, u.show_whatsapp, TRUE) AS show_whatsapp,
            COALESCE(p.show_phone, u.show_phone, TRUE) AS show_phone,
            p.available,
            p.image,
            p.title,
            p.description,
            p.created_at,
            u.username AS owner_username,
            u.full_name AS owner_name
        FROM properties p
        LEFT JOIN users u ON p.landlord_id = u.id
        WHERE 1=1
    """
    params = []

    # Rent bounds
    upper_budget = max_rent if max_rent is not None else budget
    if upper_budget is not None and float(upper_budget) > 0:
        sql += " AND p.monthly_rent_ghs <= %s"
        params.append(float(upper_budget))

    if min_rent is not None and float(min_rent) > 0:
        sql += " AND p.monthly_rent_ghs >= %s"
        params.append(float(min_rent))

    # Neighborhood / Location search
    if neighborhood and str(neighborhood).strip():
        sql += " AND LOWER(p.neighborhood) LIKE %s"
        params.append(f"%{str(neighborhood).strip().lower()}%")

    # Rooms / Bedrooms
    if min_rooms is not None and int(min_rooms) > 0:
        sql += " AND p.rooms >= %s"
        params.append(int(min_rooms))
    elif rooms is not None and int(rooms) > 0:
        sql += " AND p.rooms >= %s"
        params.append(int(rooms))

    if max_rooms is not None and int(max_rooms) > 0:
        sql += " AND p.rooms <= %s"
        params.append(int(max_rooms))

    # Bathrooms
    if min_bathrooms is not None and int(min_bathrooms) > 0:
        sql += " AND p.bathrooms >= %s"
        params.append(int(min_bathrooms))
    elif bathrooms is not None and int(bathrooms) > 0:
        sql += " AND p.bathrooms >= %s"
        params.append(int(bathrooms))

    if max_bathrooms is not None and int(max_bathrooms) > 0:
        sql += " AND p.bathrooms <= %s"
        params.append(int(max_bathrooms))

    # House type
    if house_type and str(house_type).strip().lower() not in {"all types", "any", ""}:
        sql += " AND LOWER(p.house_type) = %s"
        params.append(str(house_type).strip().lower())

    # Water
    if water and str(water).strip().lower() != "any":
        w = str(water).strip().lower()
        if w in {"yes", "available", "true"}:
            sql += " AND LOWER(p.water) LIKE '%%available%%'"
        elif w in {"no", "not available", "notavailable", "limited", "false"}:
            sql += " AND LOWER(p.water) NOT LIKE '%%available%%'"
        else:
            sql += " AND LOWER(p.water) = %s"
            params.append(w)

    # Landlord filter
    if landlord_id is not None:
        sql += " AND p.landlord_id = %s"
        params.append(int(landlord_id))

    # Availability filter
    if available_only:
        sql += " AND p.available = TRUE"

    sql += " ORDER BY p.monthly_rent_ghs ASC, p.created_at DESC"

    rows = connection.execute(sql, params).fetchall()
    return [format_property_dict(r) for r in rows]


def get_property_by_id(connection, house_id):
    """Retrieve a single property by house_id."""
    sql = """
        SELECT
            p.house_id,
            p.neighborhood,
            p.house_type,
            p.rooms,
            p.bathrooms,
            p.furnishing,
            p.distance_from_central_tamale_km,
            p.electricity,
            p.water,
            p.compound,
            p.monthly_rent_ghs,
            p.landlord_id,
            COALESCE(p.landlord_phone, u.phone, '0241234567') AS landlord_phone,
            COALESCE(p.show_whatsapp, u.show_whatsapp, TRUE) AS show_whatsapp,
            COALESCE(p.show_phone, u.show_phone, TRUE) AS show_phone,
            p.available,
            p.image,
            p.title,
            p.description,
            p.created_at,
            u.username AS owner_username,
            u.full_name AS owner_name
        FROM properties p
        LEFT JOIN users u ON p.landlord_id = u.id
        WHERE p.house_id = %s
    """
    row = connection.execute(sql, (str(house_id),)).fetchone()
    return format_property_dict(row)


def delete_all_users(confirm=False):
    """Delete all user-owned data from PostgreSQL after explicit confirmation."""
    if not confirm:
        raise ValueError("Refusing to delete users without confirm=True")
    with closing(get_connection()) as connection, connection:
        connection.execute("DELETE FROM favourites")
        connection.execute("DELETE FROM enquiries")
        connection.execute("DELETE FROM properties WHERE landlord_id IS NOT NULL")
        deleted = connection.execute("DELETE FROM users").rowcount
    return deleted
