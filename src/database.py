import os
from contextlib import closing
from pathlib import Path

import pandas as pd
import psycopg
from psycopg.rows import dict_row
from dotenv import load_dotenv

REPO_ROOT = Path(__file__).resolve().parent.parent
CSV_PATH = REPO_ROOT / "data" / "tamale_house_rentals.csv"
load_dotenv(REPO_ROOT / ".env")


def get_connection():
    """Open a PostgreSQL connection using DATABASE_URL (or POSTGRES_URL)."""
    database_url = os.environ.get("DATABASE_URL") or os.environ.get("POSTGRES_URL")
    if not database_url:
        raise RuntimeError("Set DATABASE_URL to a PostgreSQL connection string.")
    return psycopg.connect(database_url, row_factory=dict_row)


def create_users_table():
    """Create the application's PostgreSQL schema and seed initial properties."""
    with closing(get_connection()) as connection, connection:
        connection.execute("""
            CREATE TABLE IF NOT EXISTS users (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                username TEXT NOT NULL UNIQUE,
                email TEXT NOT NULL UNIQUE,
                full_name TEXT,
                password_hash TEXT NOT NULL,
                role TEXT NOT NULL CHECK (role IN ('landlord', 'tenant')),
                created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
        """)
        connection.execute("""
            CREATE UNIQUE INDEX IF NOT EXISTS users_username_lower_idx ON users (lower(username))
        """)
        connection.execute("""
            CREATE UNIQUE INDEX IF NOT EXISTS users_email_lower_idx ON users (lower(email))
        """)
        connection.execute("""
            CREATE TABLE IF NOT EXISTS properties (
                house_id TEXT PRIMARY KEY,
                neighborhood TEXT NOT NULL,
                house_type TEXT NOT NULL,
                rooms INTEGER NOT NULL,
                bathrooms INTEGER NOT NULL,
                furnishing TEXT,
                distance_from_central_tamale_km DOUBLE PRECISION,
                electricity TEXT,
                water TEXT,
                compound TEXT,
                monthly_rent_ghs DOUBLE PRECISION NOT NULL,
                landlord_id BIGINT REFERENCES users(id),
                landlord_phone TEXT DEFAULT '0241234567',
                show_whatsapp BOOLEAN NOT NULL DEFAULT TRUE,
                show_phone BOOLEAN NOT NULL DEFAULT TRUE,
                created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
        """)
        connection.execute("""
            CREATE TABLE IF NOT EXISTS favourites (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                tenant_id BIGINT NOT NULL REFERENCES users(id),
                house_id TEXT NOT NULL REFERENCES properties(house_id),
                created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                UNIQUE (tenant_id, house_id)
            )
        """)
        connection.execute("""
            CREATE TABLE IF NOT EXISTS enquiries (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                property_id TEXT NOT NULL REFERENCES properties(house_id),
                tenant_id BIGINT REFERENCES users(id),
                landlord_id BIGINT REFERENCES users(id),
                tenant_name TEXT NOT NULL,
                tenant_email TEXT NOT NULL,
                message TEXT NOT NULL,
                status TEXT NOT NULL DEFAULT 'Pending',
                created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
        """)
        seed_properties_if_empty(connection)


def _num(value, default, cast):
    try:
        if pd.isna(value):
            return default
        return cast(value)
    except (TypeError, ValueError):
        return default


def seed_properties_if_empty(connection):
    if connection.execute("SELECT EXISTS (SELECT 1 FROM properties)").fetchone()["exists"]:
        return
    if not CSV_PATH.exists():
        return

    df = pd.read_csv(CSV_PATH)
    with connection.cursor() as cursor:
        for _, row in df.iterrows():
            cursor.execute("""
                INSERT INTO properties (
                    house_id, neighborhood, house_type, rooms, bathrooms,
                    furnishing, distance_from_central_tamale_km, electricity,
                    water, compound, monthly_rent_ghs
                ) VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
                ON CONFLICT (house_id) DO NOTHING
            """, (
                row.get("house_id"), row.get("neighborhood"), row.get("house_type"),
                _num(row.get("rooms"), 1, int), _num(row.get("bathrooms"), 1, int),
                row.get("furnishing"),
                _num(row.get("distance_from_central_tamale_km"), 5.0, float),
                row.get("electricity"), row.get("water"), row.get("compound"),
                _num(row.get("monthly_rent_ghs"), 0.0, float),
            ))


def delete_all_users(confirm=False):
    """Delete all user-owned data from PostgreSQL after explicit confirmation."""
    if not confirm:
        raise ValueError("Refusing to delete users without confirm=True")
    with closing(get_connection()) as connection, connection:
        connection.execute("DELETE FROM favourites")
        connection.execute("DELETE FROM enquiries")
        connection.execute("DELETE FROM properties WHERE landlord_id IS NOT NULL")
        deleted = connection.execute("DELETE FROM users").rowcount
    return deleted
